package alex.qochinyan.first;
import java.util.List;

public class FoodAIEngine {
    public static String generateSmartAdvice(int totalCount, int expiringCount, int maxCapacity) {
        int percent = 0;
        if (maxCapacity > 0) {
            percent = (totalCount * 100) / maxCapacity;
        }
        if (totalCount == 0) {
            return "Системный анализ: Хранилище полностю пустует." +
                    "Рекомендуется составить базовый список покупок (белки, овощи) и внести их для отслеживания циклов свежести.";

        }

        if (expiringCount > 0) {
            return "Критический статус: Обнаружено [" + expiringCount + "] продуктов с истекающим сроком годности. Рекомендуется приоритетное использование данных позиций в ближайших приемах пищи для предотвращения утилизации.";

        }

        if (percent >= 85) {
            return "Внимание: Лимит загрузки превышен (" + percent + "%). Текущих запасов достаточно на длительный период. Рекомендуется временно заморозить закупки для оптимизации эргономики пространства.";

        }

        if (percent >= 40 && percent < 85) {
            return "Оптимальный баланас: Экосистема хранения стабильна. Загрузка " + percent + "%. Баланс свежести и объема идеален, плановые обновления инвентаря не требуются.";

        }

        return "Статус инвентаря: Загрузка минимальна (" + percent + "%). Продукты в полной безопасности. Рекомендуется плановое пополнение запасов во избежание дефицита.";



    }
}


